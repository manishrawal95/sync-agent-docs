import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { decisionKey } from '../plan/decisions.js';
import type { PlanItem } from '../plan/types.js';
import type { Store } from '../store/types.js';
import { blockHash, readBlocks } from './render.js';

/** A managed block whose text no longer matches what apply generated becomes a fold-or-discard question. */
export async function detectViewEdits(storeDir: string, store: Store, stage = 'plan'): Promise<PlanItem[]> {
  const items: PlanItem[] = [];
  for (const [file, hashes] of Object.entries(store.config.generated)) {
    const path = join(storeDir, file);
    let text: string;
    try {
      text = await readFile(path, 'utf8');
    } catch (err) {
      // A deleted view is regenerated by the next apply; anything else is a real problem.
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') continue;
      throw new Error(`${stage}: could not read ${path} (${(err as NodeJS.ErrnoException).code ?? (err as Error).message}). Check its permissions.`, { cause: err });
    }
    let blocks: Record<string, string>;
    try {
      blocks = readBlocks(text);
    } catch (err) {
      throw new Error(`${stage}: ${path}: ${(err as Error).message}`, { cause: err });
    }
    for (const [id, hash] of Object.entries(hashes)) {
      const body = blocks[id];
      if (body === undefined || blockHash(body) === hash) continue;
      const subject = `${file}#${id}`;
      const candidates = [blockHash(body)];
      items.push({
        key: decisionKey('view-edit', subject, candidates), tier: 'move', kind: 'view-edit', subject, candidates,
        title: `${file}: the ${id} block was edited by hand`, entityId: id.replace(/:commands$/, ''), evidence: [],
        options: ['fold', 'discard'], recommended: 'fold', answer: null, edits: {},
        notes: ['fold: the edited rows become the store facts (new rows are inferred). discard: the block is regenerated from the store.'],
      });
    }
  }
  return items;
}
