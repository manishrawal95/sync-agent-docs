import { createHash } from 'node:crypto';
import type { Store, StoreEntity, StoreFact, TruthConfig } from '../store/types.js';
import type { Attribute } from '../types.js';

export const VIEW_HEADER = '> Generated by sync-agent-docs from store/*.json. Facts live inside the sync-agent-docs blocks; text outside them is yours and is kept.';
/** `raw`, when set, is the block's text as it stands on disk, kept verbatim (an unanswered hand edit). */
export interface ViewBlock { id: string; heading: string; body: string; raw?: string }

const ATTRIBUTES = new Set<Attribute>(['port', 'ip', 'domain', 'url', 'env', 'command', 'path']);
export const beginMarker = (id: string): string => `<!-- sync-agent-docs:begin ${id} -->`;
export const endMarker = (id: string): string => `<!-- sync-agent-docs:end ${id} -->`;
export const MARKER = /^<!-- sync-agent-docs:(begin|end) (\S+) -->$/;
const FENCE = /^ {0,3}(`{3,}|~{3,})/;
export interface Marker { kind: 'begin' | 'end'; id: string }

/**
 * Each line's sync-agent-docs marker, or null. Outside a block, a fenced code block (``` or ~~~) is an
 * example someone wrote, so markers in it are not markers, unless a fence never closes. The one
 * place markers are recognised.
 */
export function markerLines(lines: string[], fences = true): (Marker | null)[] {
  let fence: string | null = null;
  let open = false;
  const marks = lines.map((line) => {
    const t = line.replace(/\r$/, '');
    if (fences && !open) {
      const f = FENCE.exec(t)?.[1];
      if (fence) {
        if (f && f[0] === fence[0] && f.length >= fence.length && t.trim() === f) fence = null;
        return null;
      }
      if (f) {
        fence = f;
        return null;
      }
    }
    const m = MARKER.exec(t.trim());
    if (!m) return null;
    open = m[1] === 'begin';
    return { kind: m[1] as Marker['kind'], id: m[2] as string };
  });
  // A fence that never closes would hide every marker after it, so such a file is read without fences.
  return fence && fences ? markerLines(lines, false) : marks;
}
/** Scanned text must not open or close an HTML comment, or it could end a block early or forge one. */
export const noComments = (s: string): string => s.replaceAll('<!--', '&lt;!--').replaceAll('-->', '--&gt;');
/** One line of scanned text: line breaks become spaces, so a value cannot start a marker or heading line. */
export const inline = (s: string): string => noComments(s.replace(/\r\n|[\r\n\u2028\u2029]/g, ' '));
/** Scanned text as a code span: an agent reads `@path` there as text, never as an import to load. */
export const code = (s: string): string => `\`${inline(s).replaceAll('`', "'")}\``;
export const cell = (s: string): string => code(s).replaceAll('|', '\\|');
/** A file name from an entity name: no separators or leading dots, so a card stays in its folder. */
const fileName = (name: string, id: string): string =>
  name.replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^[.-]+/, '') || id.replace(/[^A-Za-z0-9._-]+/g, '-');

export function blockHash(body: string): string {
  return createHash('sha256').update(body).digest('hex').slice(0, 16);
}

/** The view file an entity's facts live in, relative to the store. */
export function viewFile(v: TruthConfig['views'], e: Pick<StoreEntity, 'id' | 'kind' | 'names'>): string {
  return e.kind === 'host' ? v.hosts : e.kind === 'project' ? `${v.projects}/${fileName(e.names[0] ?? '', e.id)}.md` : v.services;
}

export function factsTable(facts: StoreFact[], notes: string): string {
  const rows = facts.map((f) => `| ${f.attribute} | ${cell(f.value)} | ${f.status} |`);
  const table = ['| Attribute | Value | Status |', '|---|---|---|', ...rows].join('\n');
  return notes.trim() ? `${table}\n\n${noComments(notes.trim())}` : table;
}

export const byFact = (a: StoreFact, b: StoreFact): number => a.attribute.localeCompare(b.attribute) || a.value.localeCompare(b.value, 'en', { numeric: true });

/** View file → its managed blocks. Projects get a card with a facts block and a Commands block. */
export function renderBlocks(store: Store): Record<string, ViewBlock[]> {
  const out: Record<string, ViewBlock[]> = {};
  for (const e of [...store.entities].sort((a, b) => a.id.localeCompare(b.id))) {
    const facts = store.facts.filter((f) => f.entityId === e.id).sort(byFact);
    const file = viewFile(store.config.views, e);
    const blocks = (out[file] ??= []);
    const name = code(e.names[0] ?? e.id);
    if (e.kind === 'project') {
      const commands = facts.filter((f) => f.attribute === 'command');
      blocks.push({ id: e.id, heading: '## Facts', body: factsTable(facts.filter((f) => f.attribute !== 'command'), e.notes) });
      blocks.push({ id: `${e.id}:commands`, heading: '## Commands', body: commands.length ? commands.map((f) => `- ${code(f.value)}`).join('\n') : 'No commands recorded yet.' });
    } else {
      blocks.push({ id: e.id, heading: `## ${name}`, body: factsTable(facts, e.notes) });
    }
  }
  return out;
}

const blockText = (b: ViewBlock): string => `${beginMarker(b.id)}\n${b.raw ?? `${b.heading}\n\n${b.body}`}\n${endMarker(b.id)}`;

/** id → text between the markers. An unclosed, nested or repeated block is refused, since merging it would lose text. */
export function readBlocks(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  let open: { id: string; lines: string[] } | null = null;
  const lines = text.split('\n');
  const marks = markerLines(lines);
  for (const [i, line] of lines.entries()) {
    const m = marks[i];
    if (!m) {
      open?.lines.push(line);
      continue;
    }
    const { kind, id } = m;
    if (kind === 'begin') {
      if (open) throw new Error(`sync-agent-docs block ${open.id} is not closed before ${id} begins. Restore its end marker or delete the block.`);
      if (id in out) throw new Error(`sync-agent-docs block ${id} appears twice. Delete the copy you do not want and run again.`);
      open = { id, lines: [] };
    } else {
      if (open?.id !== id) throw new Error(`sync-agent-docs block end ${id} has no matching begin. Restore its begin marker or delete the line.`);
      out[id] = open.lines.join('\n');
      open = null;
    }
  }
  if (open) throw new Error(`sync-agent-docs block ${open.id} has no end marker. Restore it or delete the block.`);
  return out;
}

/** Keeps every line outside the markers, replaces known blocks, drops stale ones, appends new ones, adds the header once. */
export function mergeView(existing: string | null, title: string, blocks: ViewBlock[]): string {
  const wanted = new Map(blocks.map((b) => [b.id, b]));
  if (existing === null) return `# ${title}\n\n${VIEW_HEADER}\n\n${blocks.map(blockText).join('\n\n')}\n`;
  readBlocks(existing);
  const out: string[] = [];
  const placed = new Set<string>();
  let skipping: string | null = null;
  const lines = existing.split('\n');
  const marks = markerLines(lines);
  for (const [i, line] of lines.entries()) {
    const m = marks[i];
    if (skipping) {
      if (m?.kind === 'end' && m.id === skipping) skipping = null;
      continue;
    }
    if (m?.kind === 'begin') {
      skipping = m.id;
      const b = wanted.get(m.id);
      if (b) {
        out.push(blockText(b));
        placed.add(b.id);
      } else if (out.at(-1) === '') {
        out.pop();
      }
      continue;
    }
    out.push(line);
  }
  if (!out.includes(VIEW_HEADER)) {
    const titleAt = out.findIndex((l) => /^# /.test(l));
    if (titleAt >= 0) out.splice(titleAt + 1, 0, '', VIEW_HEADER);
    else out.unshift(`# ${title}`, '', VIEW_HEADER, '');
  }
  while (out.at(-1) === '') out.pop();
  const added = blocks.filter((b) => !placed.has(b.id)).map(blockText);
  return `${[out.join('\n'), ...added].join('\n\n')}\n`;
}

/** The facts a block states: table rows, and `- \`cmd\`` lines in a Commands block. */
export function parseBlockFacts(body: string): { attribute: Attribute; value: string }[] {
  const out: { attribute: Attribute; value: string }[] = [];
  for (const raw of body.split('\n')) {
    const line = raw.trim();
    const cmd = /^- `(.+)`$/.exec(line);
    if (cmd?.[1]) {
      out.push({ attribute: 'command', value: cmd[1] });
      continue;
    }
    if (!line.startsWith('|')) continue;
    const cells = line.slice(1, line.endsWith('|') ? -1 : undefined).split(/(?<!\\)\|/).map((c) => c.trim().replaceAll('\\|', '|'));
    const [attribute, shown] = cells;
    const value = (shown && /^`(.*)`$/.exec(shown)?.[1]) || shown;
    if (attribute && value && ATTRIBUTES.has(attribute as Attribute)) out.push({ attribute: attribute as Attribute, value });
  }
  return out;
}
